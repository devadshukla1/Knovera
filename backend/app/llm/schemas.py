"""Normalised schemas for LLM requests, responses, and token telemetry (Phase 3 C3.4)."""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class MessageRole(str, Enum):
    """Supported standard chat message roles."""

    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"


class ChatMessage(BaseModel):
    """Single chat message within an LLM conversation prompt."""

    role: MessageRole = Field(..., description="Message role (system, user, assistant)")
    content: str = Field(..., min_length=1, description="Message text content")
    name: Optional[str] = Field(None, description="Optional author or entity name")


class LLMGenerationRequest(BaseModel):
    """Provider-independent generation request."""

    model: str = Field(..., min_length=1, description="Target model identifier")
    messages: List[ChatMessage] = Field(..., min_length=1, description="Ordered conversation messages")
    temperature: float = Field(default=0.2, ge=0.0, le=2.0, description="Sampling temperature")
    max_output_tokens: int = Field(default=1500, ge=1, le=8192, description="Maximum tokens to generate")
    timeout_seconds: float = Field(default=60.0, ge=1.0, le=300.0, description="Per-request timeout budget")
    response_format: Optional[str] = Field(None, description="Requested response MIME type e.g. 'json_object'")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Operational request metadata")


class TokenUsage(BaseModel):
    """Detailed token consumption telemetry."""

    input_tokens: Optional[int] = Field(None, ge=0, description="Prompt/context tokens consumed")
    output_tokens: Optional[int] = Field(None, ge=0, description="Completion tokens generated")
    total_tokens: Optional[int] = Field(None, ge=0, description="Total tokens consumed")


class LLMGenerationResponse(BaseModel):
    """Normalised provider response returned to application services."""

    model_config = ConfigDict(from_attributes=True)

    content: str = Field(..., description="Raw text generated by the model")
    provider: str = Field(..., description="Provider adapter key (e.g. 'groq', 'gemini', 'openai_compatible', 'mock')")
    requested_model: str = Field(..., description="Model identifier requested by caller")
    actual_model: Optional[str] = Field(None, description="Actual model returned by provider header/response")

    input_tokens: Optional[int] = Field(None, ge=0)
    output_tokens: Optional[int] = Field(None, ge=0)
    total_tokens: Optional[int] = Field(None, ge=0)

    finish_reason: Optional[str] = Field(None, description="Completion termination reason (e.g. 'stop', 'length')")
    request_id: Optional[str] = Field(None, description="Provider correlation/request ID")
    latency_ms: int = Field(..., ge=0, description="Round-trip generation duration in milliseconds")
    usage_metadata: Dict[str, Any] = Field(default_factory=dict, description="Provider-specific usage telemetry")
