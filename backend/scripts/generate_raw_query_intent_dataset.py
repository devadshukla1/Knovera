def build_raw_dataset() -> List[Dict[str, Any]]:
    """Builds the full raw dataset records list with deterministic IDs."""
    records = []
    global_counter = 1

    for intent_name, queries in RAW_SEED_QUERIES.items():
        for item in queries:
            example_id = f"qi_{global_counter:04d}"
            query_text = item["query"]
            attrs = {
                "requires_conversation_context": item["attrs"].get("requires_conversation_context", False),
                "requires_multi_source_evidence": item["attrs"].get("requires_multi_source_evidence", False),
                "requests_explicit_citations": item["attrs"].get("requests_explicit_citations", False),
                "contains_ambiguous_reference": item["attrs"].get("contains_ambiguous_reference", False),
            }
            records.append({
                "example_id": example_id,
                "query_text": query_text,
                "intent": intent_name,
                "attributes": attrs,
                "source_type": "synthetic_seed",
                "annotation_status": "pending_human_review",
                "taxonomy_version": TAXONOMY_VERSION,
            })
            global_counter += 1

    return records


def main() -> None:
    raw_records = build_raw_dataset()
    output_path = Path("data/query_intent/raw/query_intents.jsonl")
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        for rec in raw_records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    print(f"Generated {len(raw_records)} raw query intent records to {output_path}")


if __name__ == "__main__":
    main()
